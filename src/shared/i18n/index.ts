const bundles: Record<ResolvedUiLocale, Messages> = {
  en,
  'zh-Hant': zhHant,
  'zh-Hans': zhHans,
  ja,
};

export function normalizeBrowserLocale(value?: string | null): ResolvedUiLocale {
  const locale = (value || '').trim().toLowerCase().replace('_', '-');
  if (locale === 'zh-cn' || locale === 'zh-sg' || locale.startsWith('zh-hans')) return 'zh-Hans';
  if (
    locale === 'zh-tw' ||
    locale === 'zh-hk' ||
    locale === 'zh-mo' ||
    locale.startsWith('zh-hant')
  ) return 'zh-Hant';
  if (locale.startsWith('ja')) return 'ja';
  if (locale.startsWith('en')) return 'en';
  return 'en';
}

export function getBrowserUiLocale(): ResolvedUiLocale {
  try {
    const browserLocale = browser.i18n?.getUILanguage?.();
    if (browserLocale) return normalizeBrowserLocale(browserLocale);
  } catch {
    // Browser API may not be available in isolated unit-test contexts.
  }
  if (typeof navigator !== 'undefined') return normalizeBrowserLocale(navigator.language);
  return 'en';
}

export function resolveUiLocale(preference?: string | null): ResolvedUiLocale {
  if (preference === 'zh-Hant' || preference === 'zh-Hans' || preference === 'en' || preference === 'ja') {
    return preference;
  }
  return getBrowserUiLocale();
}

export function translate(
  localeOrPreference: string | null | undefined,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const locale = resolveUiLocale(localeOrPreference);
  let value = bundles[locale][key] ?? en[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{{${name}}}`, String(replacement));
    }
  }
  return value;
}

export function uiLanguageOptions(localeOrPreference?: string | null): Array<{ value: UiLanguage; label: string }> {
  return [
    { value: 'auto', label: translate(localeOrPreference, 'ui.followBrowser') },
    { value: 'zh-Hant', label: '繁體中文' },
    { value: 'zh-Hans', label: '简体中文' },
    { value: 'en', label: 'English' },
    { value: 'ja', label: '日本語' },
  ];
}

